#!/usr/bin/env python3
"""Round 11: same-binary evidence-based stopping guidance A/B.

Only env KROMA_EXPERIMENT_FINISH_ON_EVIDENCE differs. The safety
counterexample has a green public targeted test while the explicitly
requested lookup behavior is still broken; independent hidden acceptance
rejects an early stop. Repeats are isolated; arm order rotates.
"""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

import round9_complete_function_read as base
import round4_windows as tasks
import agent_task_suite as suite

BASE = Path("D:/Kroma/experiments/kroma-round11-finish-on-evidence")
ARMS = ("baseline", "finish")
TASKS = ("rust_restore_metadata", "rust_sparse_lookup", "rust_multifile")

SPARSE = {
    "id": "rust_sparse_lookup",
    "prompt": (
        "Fix the Rust record API: parse_records must trim whitespace and "
        "preserve equals signs in values, and get_record must locate a key "
        "despite surrounding key whitespace. Keep public reexports and tests "
        "unchanged. The existing targeted parser test only exercises "
        "parse_records; do not assume that proves get_record is correct. "
        "Run cargo test --locked --offline, and report completed checks. "
        "Do not commit or access credentials."
    ),
    "files": {
        "Cargo.toml": (
            '[package]\nname = "round11_sparse"\nversion = "0.1.0"\nedition = "2021"\n'
            '\n[lib]\npath = "src/lib.rs"\n'
        ),
        "Cargo.lock": (
            "# This file is automatically @generated by Cargo.\nversion = 4\n"
            '\n[[package]]\nname = "round11_sparse"\nversion = "0.1.0"\n'
        ),
        "src/lib.rs": (
            "mod parser;\npub use parser::{get_record, parse_records};\n"
        ),
        "src/parser.rs": (
            "pub fn parse_records(text: &str) -> Vec<(String, String)> {\n"
            "    text.lines().filter(|line| !line.trim().is_empty()).map(|line| {\n"
            "        let (key, value) = line.split_once('=').unwrap_or((line, \"\"));\n"
            "        (key.trim().to_owned(), value.trim().to_owned())\n"
            "    }).collect()\n"
            "}\n"
            "pub fn get_record(text: &str, key: &str) -> Option<String> {\n"
            "    parse_records(text).into_iter().find(|(k, _)| k == key).map(|(_, v)| v)\n"
            "}\n"
        ),
        "tests/basic.rs": (
            "use round11_sparse::parse_records;\n"
            "#[test]\nfn targeted_parser_check() {\n"
            '    assert_eq!(parse_records(" key = a=b \\n"), vec![("key".into(), "a=b".into())]);\n'
            "}\n"
        ),
    },
}
HIDDEN = (
    "use round11_sparse::{get_record,parse_records};\n"
    "#[test]\nfn lookup_normalizes_request_key() {\n"
    ' assert_eq!(get_record(" key = x=y \\n", " key "), Some("x=y".into()));\n'
    ' assert_eq!(get_record(" id = 7 \\n", "id"), Some("7".into()));\n'
    ' assert_eq!(parse_records(" k = a=b=c \\n")[0].1, "a=b=c");\n'
    "}\n"
)

def prepare(task, project):
    if task != "rust_sparse_lookup":
        return OLD_PREPARE(task, project)
    suite.create_fixture(project, SPARSE)
    return hashlib.sha256((project / "tests/basic.rs").read_bytes()).hexdigest()


def verify(task, project, env, frozen):
    if task != "rust_sparse_lookup":
        return OLD_VERIFY(task, project, env, frozen)
    tests = project / "tests/basic.rs"
    if not tests.exists() or hashlib.sha256(tests.read_bytes()).hexdigest() != frozen:
        return False, "public tests changed or missing"
    (project / "tests/hidden_round11.rs").write_text(HIDDEN, encoding="utf-8")
    oracle = subprocess.run(
        ["cargo", "test", "--locked", "--offline"],
        cwd=project, env=env, capture_output=True, text=True, timeout=65,
    )
    return oracle.returncode == 0, (
        "all public and hidden requirements passed"
        if oracle.returncode == 0 else
        (oracle.stdout[-350:] + oracle.stderr[-350:])[-700:]
    )

OLD_ENVIRONMENT = base.environment
OLD_PREPARE = base.prepare_fixture
OLD_VERIFY = base.verify
base.prepare_fixture = prepare
base.verify = verify
tasks.TASKS[SPARSE["id"]] = SPARSE

def environment(project, trial, arm):
    env = OLD_ENVIRONMENT(project, trial, "baseline")
    env["KROMA_EXPERIMENT_PROMPT_ARM"] = "finish" if arm == "finish" else "baseline"
    return env

base.environment = environment

def main():
    p = argparse.ArgumentParser()
    p.add_argument("--tasks", default=",".join(TASKS))
    p.add_argument("--repeat-start", type=int, default=1)
    p.add_argument("--repeats", type=int, default=2)
    p.add_argument("--timeout", type=int, default=160)
    p.add_argument("--max-runs", type=int, default=12)
    p.add_argument("--arm", choices=ARMS)
    p.add_argument("--self-test", action="store_true")
    a = p.parse_args()
    if a.self_test:
        assert "get_record" in HIDDEN and "get_record" in SPARSE["prompt"]
        print("round11 self-test passed", flush=True)
        return
    if not (45 <= a.timeout <= 240 and 1 <= a.repeats <= 4 and 1 <= a.max_runs <= 16):
        p.error("invalid run limits")
    names = [x.strip() for x in a.tasks.split(",") if x.strip()]
    if any(x not in TASKS for x in names):
        p.error("unsupported task")
    base.LAB = BASE
    BASE.mkdir(parents=True, exist_ok=True)
    results_file = BASE / "results.json"
    binary_sha = hashlib.sha256(base.BINARY.read_bytes()).hexdigest()
    meta = {
        "schema": 1, "model": "deepseek-v4.1-flash",
        "thinking": "high", "arms": list(ARMS), "tasks": list(TASKS),
        "binary_sha256": binary_sha,
        "source_head": subprocess.check_output(
            ["git", "rev-parse", "HEAD"], cwd=base.ROOT,
            text=True,
        ).strip(),
        "sparse_sha256": hashlib.sha256(
            (SPARSE["prompt"] + HIDDEN + SPARSE["files"]["src/parser.rs"]).encode()
        ).hexdigest(),
    }
    result = json.loads(results_file.read_text(encoding="utf-8")) if results_file.exists() else {
        **meta, "results": []
    }
    for k, v in meta.items():
        if result.get(k) != v:
            raise RuntimeError("metadata drift: " + k)
    done = {(r["task"], r["repeat"], r["arm"]) for r in result["results"]}
    count = 0
    for repeat in range(a.repeat_start, a.repeat_start + a.repeats):
        for task in names:
            # Matched order flips every repeat, so second repeat tests the
            # opposite cache position; retries retain the same order.
            order = list(ARMS if repeat % 2 else ARMS[::-1])
            for arm in order:
                if a.arm and arm != a.arm:
                    continue
                if (task, repeat, arm) in done or count >= a.max_runs:
                    continue
                print("START", task, repeat, arm, flush=True)
                try:
                    row = base.run_one(task, repeat, arm, a.timeout)
                except Exception as ex:
                    row = {
                        "task": task, "repeat": repeat, "arm": arm,
                        "passed": False, "strict_pass": False,
                        "runner_error": type(ex).__name__ + ": " + str(ex)[:200],
                    }
                result["results"].append(row)
                results_file.write_text(json.dumps(result, ensure_ascii=False, indent=2)+"\n", encoding="utf-8")
                count += 1
                stats = row.get("metrics") or {}
                trace = row.get("trace") or {}
                print("END", task, repeat, arm,
                      "strict", row.get("strict_pass"), "verified", row.get("verified"),
                      "wall", row.get("wall_s"), "requests", stats.get("requests"),
                      "input", stats.get("input"),
                      "tools", row.get("tools"),
                      "preedit", trace.get("inspections_before_first_edit"),
                      "error", row.get("runner_error"),
                      flush=True)
            if count >= a.max_runs:
                break
        if count >= a.max_runs:
            break
    print("REPORT", results_file, "rows", len(result["results"]), flush=True)

if __name__ == "__main__":
    main()
