def event(line: str) -> dict:
    try:
        value = json.loads(line)
        return value if isinstance(value, dict) else {}
    except (ValueError, TypeError):
        return {}


def int_or_none(obj: dict, key: str):
    value = obj.get(key)
    return value if type(value) is int and value >= 0 else None


def aggregate_field(rows: list[dict], key: str):
    parts = [int_or_none(row, key) for row in rows]
    if any(value is None for value in parts):
        return None
    return sum(parts)


def parse_pi(raw: str) -> tuple[dict, str, list[dict]]:
    messages = []
    uses = []
    tools = []
    active = {}
    for line in raw.splitlines():
        v = event(line)
        kind = v.get("type")
        if kind == "message_end" and (v.get("message") or {}).get("role") == "assistant":
            msg = v["message"]
            messages.append(msg)
            uses.append(msg.get("usage") or {})
        elif kind == "tool_execution_start":
            args = v.get("args") or {}
            args = args if isinstance(args, dict) else {}
            cmd = str(args.get("command") or args.get("path") or "")
            row = {"tool": v.get("toolName") or "unknown", "operation": classify(cmd),
                   "signature": hashlib.sha256((str(v.get("toolName")) + ":" + cmd).encode()).hexdigest()[:12]}
            tools.append(row)
            active[v.get("toolCallId")] = row
        elif kind == "tool_execution_end":
            row = active.get(v.get("toolCallId"))
            if row is not None:
                row["duration_ms"] = v.get("durationMs")
    answer = "\n".join(
        part.get("text", "") for msg in messages for part in msg.get("content", [])
        if isinstance(part, dict) and part.get("type") == "text"
    )
    inputs = [aggregate_field([u], "input") for u in uses]
    reads = [aggregate_field([u], "cacheRead") for u in uses]
    writes = [aggregate_field([u], "cacheWrite") for u in uses]
    totals = [None if any(x is None for x in row) else sum(row)
              for row in zip(inputs, reads, writes)]
    metric = {
        "requests": len(uses),
        "input": sum(totals) if all(x is not None for x in totals) else None,
        "uncached": sum(inputs) if all(x is not None for x in inputs) else None,
        "cached": sum(reads) if all(x is not None for x in reads) else None,
        "cache_write": sum(writes) if all(x is not None for x in writes) else None,
        "output": aggregate_field(uses, "output"),
        "reasoning": aggregate_field(uses, "reasoning"),
        "missing_usage": any(not u or any(key not in u for key in ("input", "output", "cacheRead", "cacheWrite")) for u in uses),
        "errors": sum(msg.get("stopReason") in ("error", "aborted") for msg in messages),
    }
    return metric, answer, tools


def parse_kroma(out: str, err: str, session: Path) -> tuple[dict, str, list[dict], dict]:
    metrics = suite.parse_usage(err)
    profile = suite.parse_profile(err)
    count = 0
    failed = 0
    for line in err.splitlines():
        if line.startswith("[usage] task_status="):
            m = re.search(r"model_requests=(\d+).*failed_model_requests=(\d+)", line)
            if m:
                count, failed = int(m.group(1)), int(m.group(2))
    tools = []
    journal = Path(str(session) + ".wal")
    if journal.is_file():
        for line in journal.read_text(encoding="utf-8", errors="replace").splitlines():
            v = event(line.split("\t", 1)[0])
            message = v.get("message") or {}
            if message.get("role") != "assistant":
                continue
            for call in message.get("tool_calls") or []:
                fn = call.get("function") or {}
                raw = fn.get("arguments") or "{}"
                args = event(raw)
                cmd = str(args.get("command") or args.get("path") or "")
                tool = fn.get("name") or "unknown"
                tools.append({"tool": tool, "operation": classify(cmd),
                              "signature": hashlib.sha256((tool + ":" + cmd).encode()).hexdigest()[:12]})
    metrics["failed_requests"] = failed
    if count:
        metrics["requests"] = count
    metrics["missing_usage"] = metrics.get("input") is None or metrics.get("output") is None
    metrics["uncached"] = (
        metrics["input"] - metrics["cached"]
        if metrics.get("input") is not None and metrics.get("cached") is not None else None
    )
    return metrics, out, tools, profile


def classify(cmd: str) -> str:
    low = cmd.lower()
    if "cargo test" in low or "unittest" in low or "pytest" in low:
        return "test"
    if re.search(r"\b(rg|grep|find|ls|dir|head|tail|cat|type|read)\b", low):
        return "inspect"
    if "write_text" in low or " > " in low or "echo " in low or "edit" in low:
        return "edit"
    return "other"


def version(command: list[str]) -> str:
    result = subprocess.run(command, capture_output=True, text=True, timeout=30)
    if result.returncode:
        raise RuntimeError("cannot check tool version")
    return result.stdout.strip().splitlines()[0]


def hash_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as reader:
        for block in iter(lambda: reader.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


