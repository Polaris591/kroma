def prepare_rust_wal_fixture(project: Path):
    """Inject an independently tested WAL-ordering regression into HEAD sources.

    The archived 2026-10-28 fixture depended on a removed literal expression.
    Current versions use session::journal_path; the behavior under test is
    unchanged. Source comes from the committed HEAD, not this dirty worktree.
    """
    import io
    import tarfile
    archive = subprocess.check_output(["git", "archive", "HEAD"], cwd=ROOT)
    with tarfile.open(fileobj=io.BytesIO(archive), mode="r:") as jar:
        jar.extractall(project, filter="data")
    path = project / "src" / "sessions.rs"
    source = path.read_text(encoding="utf-8")
    original = (
        "                // The JSON checkpoint can be old while the WAL contains the\n"
        "                // latest turns; order by the most recent durable write.\n"
        "                let wal = crate::session::journal_path(&path);\n"
        "                let modified = entry\n"
        "                    .metadata()?\n"
        "                    .modified()\n"
        "                    .ok()\n"
        "                    .into_iter()\n"
        "                    .chain(fs::metadata(wal).and_then(|meta| meta.modified()).ok())\n"
        "                    .max();"
    )
    broken = (
        "                // Regression: recent sessions incorrectly ignore the WAL.\n"
        "                let modified = entry.metadata()?.modified().ok();"
    )
    if source.count(original) != 1:
        raise RuntimeError("fixture drift: cannot find current WAL-ordering implementation")
    regression = """
#[cfg(test)]
mod engineering_regression {
    use super::*;

    #[test]
    fn wal_append_controls_recent_session_order() {
        let root = std::env::temp_dir().join(format!(
            "kroma-round5-wal-{}-{}", std::process::id(),
            NEXT_SESSION_ID.fetch_add(1, Ordering::Relaxed)
        ));
        fs::create_dir_all(&root).unwrap();
        let catalog = SessionCatalog::from_default(root.join("sample.json")).unwrap();
        let alpha = root.join("sample--alpha.json");
        let bravo = root.join("sample--bravo.json");
        fs::write(&alpha, "checkpoint").unwrap();
        std::thread::sleep(std::time::Duration::from_millis(1100));
        fs::write(&bravo, "checkpoint").unwrap();
        assert_eq!(catalog.list().unwrap()[0].id, "bravo");
        std::thread::sleep(std::time::Duration::from_millis(1100));
        fs::write(crate::session::journal_path(&alpha), "newer WAL entry").unwrap();
        assert_eq!(catalog.list().unwrap()[0].id, "alpha");
        fs::remove_dir_all(root).unwrap();
    }
}
"""
    path.write_text(source.replace(original, broken) + regression, encoding="utf-8")


def run_one(lab: Path, kroma: Path, task: dict, repeat: int, runner: str, timeout: int) -> dict:
    trial = lab / task["id"] / str(repeat) / runner
    project = trial / "project"
    project.mkdir(parents=True, exist_ok=False)
    frozen_regression = None
    if task["id"] == "rust_wal_regression":
        prepare_rust_wal_fixture(project)
        source = (project / "src" / "sessions.rs").read_text(encoding="utf-8")
        marker = "\n#[cfg(test)]\nmod engineering_regression"
        assert marker in source, "injected regression fixture missing"
        frozen_regression = marker + source.split(marker, 1)[1]
        assert "fn wal_append_controls_recent_session_order()" in frozen_regression
    else:
        suite.create_fixture(project, task)
    env = {key: value for key, value in os.environ.items() if not key.startswith("KROMA_")}
    if task["id"] == "rust_wal_regression":
        env["CARGO_TARGET_DIR"] = "D:/Kroma/target-kroma-check"
        env["CARGO_INCREMENTAL"] = "0"
    elif task["id"] == "rust_multifile":
        env["CARGO_TARGET_DIR"] = str(lab / "rust-target" / runner)
    if runner == "pi":
        command = [str(PI), *PI_ARGS, task["prompt"]]
    else:
        env.update({
            "KROMA_PROVIDER_PROFILE": "deepseek",
            "KROMA_DEEPSEEK_THINKING": "off",
            "KROMA_REASONING_EFFORT": "high",
            "KROMA_PROFILE": "1",
            # Match Pi --no-extensions without modifying user plugin state.
            "KROMA_PLUGIN_DIR": str(trial / "disabled-global-plugins" / "plugins"),
            "KROMA_WORKDIR": str(project),
            "KROMA_SESSION_FILE": str(trial / "session.json"),
        })
        command = [str(kroma), "--print", "--no-mcp", task["prompt"]]
    started = time.monotonic()
    proc = subprocess.Popen(
        command, cwd=project, env=env, stdin=subprocess.DEVNULL,
        stdout=subprocess.PIPE, stderr=subprocess.PIPE,
        creationflags=subprocess.CREATE_NEW_PROCESS_GROUP if sys.platform == "win32" else 0,
    )
    timed_out = False
    try:
        stdout, stderr = proc.communicate(timeout=timeout)
    except subprocess.TimeoutExpired:
        timed_out = True
        if sys.platform == "win32":
            subprocess.run(["taskkill", "/PID", str(proc.pid), "/T", "/F"],
                           capture_output=True, timeout=20)
        else:
            proc.kill()
        stdout, stderr = proc.communicate(timeout=15)
    wall = round(time.monotonic() - started, 3)
    (trial / "stdout.log").write_bytes(stdout)
    (trial / "stderr.log").write_bytes(stderr)
    out, err = stdout.decode("utf-8", "replace"), stderr.decode("utf-8", "replace")
    if runner == "pi":
        metrics, answer, tools = parse_pi(out)
        profile = {}
    else:
        metrics, answer, tools, profile = parse_kroma(out, err, trial / "session.json")
    try:
        if task["id"] == "rust_wal_regression":
            source = (project / "src" / "sessions.rs").read_text(encoding="utf-8")
            if source.count("fn wal_append_controls_recent_session_order()") != 1 \
                    or source.count(frozen_regression) != 1:
                verified = False
            else:
                oracle = subprocess.run(
                    ["cargo", "test", "--locked", "--offline", "--quiet",
                     "wal_append_controls_recent_session_order"],
                    cwd=project, env=env, capture_output=True, text=True, timeout=100,
                )
                verified = oracle.returncode == 0
        elif task["id"] == "rust_multifile":
            (project / "tests" / "hidden_round4.rs").write_text(HIDDEN_RUST_TEST, encoding="utf-8")
            oracle = subprocess.run(
                ["cargo", "test", "--locked", "--offline", "--quiet"],
                cwd=project, env=env, capture_output=True, text=True, timeout=65,
            )
            verified = oracle.returncode == 0
        else:
            verified = bool(suite.verify(project, task["id"], answer))
    except Exception:
        verified = False
    types = Counter(x["tool"] for x in tools)
    operations = Counter(x["operation"] for x in tools)
    repeats = Counter(x["signature"] for x in tools)
    summary = {
        "task": task["id"], "repeat": repeat, "runner": runner,
        "wall_s": wall, "exit": proc.returncode, "timeout": timed_out,
        "verified": verified, "passed": bool(verified and proc.returncode == 0 and not timed_out),
        "metrics": metrics, "profile": profile, "tools": len(tools),
        "tool_types": dict(types), "operations": dict(operations),
        "duplicate_exact_tool_calls": sum(count - 1 for count in repeats.values() if count > 1),
        "logs": str(trial),
    }
    return summary


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--lab", type=Path, default=DEFAULT_LAB)
    parser.add_argument("--kroma", type=Path, default=DEFAULT_KROMA)
    parser.add_argument("--tasks", default="exact_lookup,fix_arithmetic,implement_records")
    parser.add_argument("--repeat-start", type=int, default=1)
    parser.add_argument("--repeats", type=int, default=1)
    parser.add_argument("--timeout", type=int, default=105)
    parser.add_argument("--max-runs", type=int, default=4)
    parser.add_argument("--runner", choices=("pi", "kroma", "both"), default="both")
    parser.add_argument("--self-test", action="store_true")
    a = parser.parse_args()
    if a.self_test:
        suite.self_test()
        pi_usage, pi_answer, _ = parse_pi(json.dumps({"type":"message_end","message":{
            "role":"assistant","content":[{"type":"text","text":"OK"}],
            "usage":{"input":100,"cacheRead":25,"cacheWrite":3,"output":7,"reasoning":2}
        }}))
        assert pi_usage["input"] == 128 and pi_usage["cached"] == 25 and pi_answer == "OK"
        print("round4 parser self-test OK", flush=True)
        return
    selected = [task.strip() for task in a.tasks.split(",") if task.strip()]
    if not selected or any(task not in TASKS for task in selected):
        parser.error("unknown task")
    if not (1 <= a.repeats <= 6 and 1 <= a.timeout <= 300 and 1 <= a.max_runs <= 24):
        parser.error("invalid repeats/timeout/limit")
    kroma = a.kroma.resolve()
    if not kroma.is_file() or not PI.is_file():
        raise RuntimeError("missing release Kroma or installed Pi CLI")
    lab = a.lab.resolve()
    lab.mkdir(parents=True, exist_ok=True)
    report_file = lab / "results.json"
    fresh = initial_report(lab, kroma)
    if report_file.exists():
        report = json.loads(report_file.read_text(encoding="utf-8"))
        for key in ("schema", "seed", "pi_version", "kroma_sha256", "model", "thinking"):
            if report.get(key) != fresh[key]:
                raise RuntimeError(f"existing report differs in {key}; use new lab")
    else:
        report = fresh
        report_file.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    done = {(r["task"], r["repeat"], r["runner"]) for r in report["results"]}
    pairs = [(name, rep) for name in selected
             for rep in range(a.repeat_start, a.repeat_start + a.repeats)]
    rng = random.Random(SEED)
    rng.shuffle(pairs)
    runs = 0
    for task_id, rep in pairs:
        order = ["pi", "kroma"]
        rng.shuffle(order)
        if a.runner != "both":
            order = [a.runner]
        for runner in order:
            key = task_id, rep, runner
            if key in done:
                continue
            if runs >= a.max_runs:
                break
            print(f"START task={task_id} repeat={rep} runner={runner}", flush=True)
            try:
                row = run_one(lab, kroma, TASKS[task_id], rep, runner, a.timeout)
            except Exception as error:
                row = {"task":task_id,"repeat":rep,"runner":runner,"passed":False,
                       "error":f"{type(error).__name__}: {str(error)[:180]}"}
            report["results"].append(row)
            report_file.write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
            done.add(key)
            runs += 1
            metrics = row.get("metrics") or {}
            print(f"END task={task_id} rep={rep} runner={runner} "
                  f"passed={row.get('passed')} wall={row.get('wall_s')} "
                  f"requests={metrics.get('requests')} input={metrics.get('input')} "
                  f"cached={metrics.get('cached')} output={metrics.get('output')} "
                  f"tools={row.get('tools')}", flush=True)
        if runs >= a.max_runs:
            break
    print(f"REPORT {report_file}; rows={len(report['results'])}", flush=True)


if __name__ == "__main__":
    main()
